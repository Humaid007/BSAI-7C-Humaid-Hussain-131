from __future__ import annotations
import random
import time
from pathlib import Path
import tkinter as tk
from tkinter import simpledialog, messagebox

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

OUT = Path(__file__).resolve().parent
N_PARTICIPANTS = 5
GRID_ROWS, GRID_COLS = 10, 12
PANELS = {
    1: "Panel 1 — baseline grid",
    2: "Panel 2 — baseline grid (new layout)",
    3: "Panel 3 — size only",
    4: "Panel 4 — colour + shape (redundant coding)",
}
# Use a fixed random seed only for reproducibility of grid generation.
# Panel order is independently shuffled for every participant.
rng = random.Random(601220)

def make_grid(panel: int, seed: int):
    """Return display cells: digit, size, colour, shape."""
    rr = random.Random(seed)
    cells = []
    target_count = rr.randint(8, 13)
    target_positions = set(rr.sample(range(GRID_ROWS * GRID_COLS), target_count))
    for idx in range(GRID_ROWS * GRID_COLS):
        is_target = idx in target_positions
        digit = "3" if is_target else rr.choice(["0", "1", "2", "4", "5", "6", "7", "8", "9"])
        size = 19 if (panel == 3 and is_target) else 12
        colour = "#c0392b" if (panel == 4 and is_target) else "#202020"
        shape = "◆" if (panel == 4 and is_target) else "●"
        cells.append((digit, size, colour, shape, is_target))
    return cells, target_count

def show_trial(root, panel, participant_no, trial_no):
    cells, correct_count = make_grid(panel, seed=10000 * participant_no + panel * 97 + trial_no)
    win = tk.Toplevel(root)
    win.title(f"Participant {participant_no} — {PANELS[panel]}")
    win.attributes("-topmost", True)
    tk.Label(win, text=f"Count the number of 3s. Press SPACE when ready, then count as quickly and accurately as possible.",
             font=("Arial", 12), wraplength=850).pack(padx=12, pady=10)
    frame = tk.Frame(win)
    frame.pack(padx=12, pady=10)
    for i, (digit, size, colour, shape, is_target) in enumerate(cells):
        # Panel 4 redundantly encodes target with both colour and shape;
        # the target digit remains 3 in every panel.
        label = tk.Label(frame, text=digit, font=("Arial", size, "bold"),
                         fg=colour, width=2, height=1)
        label.grid(row=i // GRID_COLS, column=i % GRID_COLS, padx=2, pady=2)
        if panel == 4 and is_target:
            label.config(text="3◆")
        elif panel == 4:
            label.config(text=digit)
    status = tk.Label(win, text="Press SPACE to reveal the grid and start timing.",
                      font=("Arial", 11))
    status.pack(pady=6)
    state = {"start": None, "elapsed": None, "started": False}
    def start(_event=None):
        if not state["started"]:
            state["started"] = True
            state["start"] = time.perf_counter()
            status.config(text="Timing… Count the 3s, then press ENTER.")
    def finish(_event=None):
        if state["started"] and state["elapsed"] is None:
            state["elapsed"] = time.perf_counter() - state["start"]
            win.destroy()
    win.bind("<space>", start)
    win.bind("<Return>", finish)
    win.focus_force()
    root.wait_window(win)
    if state["elapsed"] is None:
        return None, correct_count
    return round(state["elapsed"], 3), correct_count

def make_chart(results: pd.DataFrame):
    order = [PANELS[i] for i in range(1, 5)]
    fig, ax = plt.subplots(figsize=(10, 6), constrained_layout=True)
    means = results.groupby("panel_name")["seconds"].mean().reindex(order)
    ax.bar(range(4), means.values, alpha=0.28, width=0.62, color="#4C78A8", zorder=1)
    jitter = random.Random(91)
    for x, name in enumerate(order):
        vals = results.loc[results["panel_name"] == name, "seconds"].dropna().tolist()
        xs = [x + jitter.uniform(-0.13, 0.13) for _ in vals]
        ax.scatter(xs, vals, color="#24557A", edgecolor="white", linewidth=0.7,
                   s=55, alpha=0.9, zorder=3)
    ax.set_xticks(range(4), ["1 Baseline", "2 Baseline\n(new layout)", "3 Size only", "4 Colour + shape"])
    ax.set_ylabel("Time to count 3s (seconds)")
    ax.set_xlabel("Panel")
    ax.set_ylim(bottom=0)
    ax.set_title("Observed counting times vary by visual encoding")
    ax.grid(axis="y", alpha=0.2, zorder=0)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    ax.text(0.01, -0.22,
            "Source: CDB601220 class experiment; synthetic stimuli generated by this script. "
            "n = 5 classmates. Each participant saw panels in an independently randomised order.",
            transform=ax.transAxes, fontsize=8, va="top", wrap=True)
    fig.savefig(OUT / "popout_experiment_chart.png", dpi=300, bbox_inches="tight")
    plt.close(fig)

def main():
    root = tk.Tk()
    root.withdraw()
    rows = []
    for pno in range(1, N_PARTICIPANTS + 1):
        participant = simpledialog.askstring("Participant", f"Enter anonymous participant code for classmate {pno} (e.g. P{pno}):", parent=root)
        if not participant:
            participant = f"P{pno}"
        order = [1, 2, 3, 4]
        rng.shuffle(order)
        messagebox.showinfo("Experiment", f"Participant {participant}: panel order is {', '.join(map(str, order))}.\nDo not coach or reveal the target count.", parent=root)
        for trial_no, panel in enumerate(order, start=1):
            elapsed, correct_count = show_trial(root, panel, pno, trial_no)
            if elapsed is None:
                messagebox.showwarning("Trial skipped", "No valid timing captured. Please rerun this participant/panel.", parent=root)
                continue
            answer = simpledialog.askinteger("Response", f"{participant}, panel {panel}: how many 3s did you count?", parent=root, minvalue=0)
            correct = (answer == correct_count)
            rows.append({"participant": participant, "panel": panel, "panel_name": PANELS[panel],
                         "order_position": trial_no, "seconds": elapsed, "answer": answer,
                         "correct_count": correct_count, "correct": correct})
    root.destroy()
    if not rows:
        print("No trials recorded; no chart generated.")
        return
    df = pd.DataFrame(rows)
    df.to_csv(OUT / "popout_experiment_results.csv", index=False)
    make_chart(df)
    summary = df.groupby("panel_name")["seconds"].agg(["count", "mean", "std"]).round(3)
    print("\nObserved times (seconds):")
    print(summary.to_string())
    print("\nAccuracy by panel:")
    print(df.groupby("panel_name")["correct"].mean().round(3).to_string())
    print("\nWrote popout_experiment_results.csv and popout_experiment_chart.png")
    print("Report the actual fastest and slowest channels from these results; do not invent or pre-fill results.")

if __name__ == "__main__":
    main()
